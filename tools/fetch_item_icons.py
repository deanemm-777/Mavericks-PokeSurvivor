#!/usr/bin/env python3
"""
Standalone build (Doofcraft update 40): held-item icons from PokeRogue
(pagefaultgames/pokerogue-assets, images/items.png), turned into the pixel
"rows" format of ui/icons.js. Choice Band, Life Orb, Rocky Helmet and Assault
Vest keep their own art, as in Doofcraft. Writes js/data/item-icons.js.

    python3 tools/fetch_item_icons.py
"""
import io, json, os, string, urllib.request
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = 'https://raw.githubusercontent.com/pagefaultgames/pokerogue-assets/beta/images/'
ICONS = {'leftovers': 'leftovers', 'quickclaw': 'quick_claw', 'focussash': 'focus_sash', 'shellbell': 'shell_bell',
         'amuletcoin': 'amulet_coin', 'luckyegg': 'lucky_egg', 'choicescarf': 'choice_scarf', 'scopelens': 'scope_lens',
         'muscleband': 'muscle_band', 'wiseglasses': 'wise_glasses'}
CHARS = string.ascii_letters.replace('k', '') + string.digits


def get(name):
    return urllib.request.urlopen(BASE + name, timeout=30).read()


def main():
    atlas = Image.open(io.BytesIO(get('items.png'))).convert('RGBA')
    frames = {f['filename']: f for f in json.loads(get('items.json'))['textures'][0]['frames']}
    out = {}
    for ours, theirs in ICONS.items():
        f = frames[theirs]
        x, y, w, h = (f['frame'][k] for k in ('x', 'y', 'w', 'h'))
        im = atlas.crop((x, y, x + w, y + h))
        S = max(w, h)
        canvas = Image.new('RGBA', (S, S), (0, 0, 0, 0))
        canvas.paste(im, ((S - w) // 2, (S - h) // 2))
        pal, rows = {}, []
        for yy in range(S):
            row = ''
            for xx in range(S):
                r, g, b, a = canvas.getpixel((xx, yy))
                if a < 128:
                    row += '.'
                    continue
                hexc = '#%02x%02x%02x' % (r, g, b)
                if hexc not in pal:
                    pal[hexc] = CHARS[len(pal)] if len(pal) < len(CHARS) else '.'
                row += pal[hexc]
            rows.append(row)
        out[ours] = {'pal': {v: k for k, v in pal.items() if v != '.'}, 'rows': rows, 'ext': 1}
        print(f'  {ours}: {S}x{S}, {len(pal)} colours')
    with io.open(os.path.join(ROOT, 'js', 'data', 'item-icons.js'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('/* ============ item-icons.js — GENERATED by tools/fetch_item_icons.py, do not edit ============\n'
                 ' * Held-item icons from PokeRogue (update 40). Loaded after ui/icons.js: they replace its drawings.\n */\n')
        fh.write('Object.assign(G.Icons.UI, ' + json.dumps(out, separators=(',', ':')) + ');\n')
    print('Wrote js/data/item-icons.js')


if __name__ == '__main__':
    main()
