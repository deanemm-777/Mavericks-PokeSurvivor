#!/usr/bin/env python3
"""
Standalone build: Doofcraft update 42's Waves boss, Giratina.

  - Giratina (Origin Forme) from SpriteCollab 0487/0001, under pseudo number 28487
    (Giratina's Altered Forme is the normal 487)

Writes js/data/giratina.js (its sprite metadata).

    python3 tools/fetch_update42.py
"""
import io
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fetch_update40 as u40  # noqa: E402
import fetch_sprites as fs  # noqa: E402

OUT_JS = os.path.join(fs.ROOT, 'js', 'data', 'giratina.js')


def main():
    meta = {28487: u40.download('0487/0001', os.path.join(fs.OUT_ASSETS, '28487'))}
    print('  28487: Giratina (Origin Forme)' + (' + shiny' if meta[28487].get('sh') else ''))
    with io.open(OUT_JS, 'w', encoding='utf-8', newline='\n') as f:
        f.write('/* ============ giratina.js — GENERATED by tools/fetch_update42.py, do not edit ============\n'
                ' * Giratina (Origin Forme), the Halloween Waves round-25 boss from Doofcraft update 42.\n */\n'
                'Object.assign(G.SPRITE_META, ' + json.dumps({str(k): v for k, v in meta.items()}, separators=(',', ':')) + ');\n')
    print('Wrote', OUT_JS)


if __name__ == '__main__':
    main()
