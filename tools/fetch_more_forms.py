#!/usr/bin/env python3
"""
Standalone build: Arceus's plate forms and Eternamax Eternatus (SpriteCollab).

  Arceus 0493/0001-0017 (one per type) -> pseudo numbers 26001-26017
  Eternamax Eternatus 0890/0001        -> pseudo number 27890

Writes js/data/more-forms.js (sprite metadata and G.PLATES).

    python3 tools/fetch_more_forms.py
"""
import io, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fetch_sprites as fs  # noqa: E402

PLATES = [  # SpriteCollab form, type, plate
    ('0001', 'bug', 'Insect Plate'), ('0002', 'dark', 'Dread Plate'), ('0003', 'dragon', 'Draco Plate'),
    ('0004', 'electric', 'Zap Plate'), ('0005', 'fighting', 'Fist Plate'), ('0006', 'fire', 'Flame Plate'),
    ('0007', 'flying', 'Sky Plate'), ('0008', 'ghost', 'Spooky Plate'), ('0009', 'grass', 'Meadow Plate'),
    ('0010', 'ground', 'Earth Plate'), ('0011', 'ice', 'Icicle Plate'), ('0012', 'poison', 'Toxic Plate'),
    ('0013', 'psychic', 'Mind Plate'), ('0014', 'rock', 'Stone Plate'), ('0015', 'steel', 'Iron Plate'),
    ('0016', 'water', 'Splash Plate'), ('0017', 'fairy', 'Pixie Plate'),
]
OUT_JS = os.path.join(fs.ROOT, 'js', 'data', 'more-forms.js')


def download(tag, out_dir):
    xml = fs.fetch(f'{fs.BASE}/{tag}/AnimData.xml')
    if not xml:
        return None
    anims, shadow = fs.parse_animdata(xml.decode('utf-8', 'replace'))
    normal = fs.download_set(f'{fs.BASE}/{tag}', out_dir, anims)
    if not (fs.REQUIRED & set(normal)):
        return None
    meta = {'s': shadow, 'a': normal}
    sxml = fs.fetch(f'{fs.BASE}/{tag}/0001/AnimData.xml')
    if sxml:
        sanims = fs.parse_animdata(sxml.decode('utf-8', 'replace'))[0]
        sh = fs.download_set(f'{fs.BASE}/{tag}/0001', os.path.join(out_dir, 's'), sanims, normal)
        if 'Idle' in sh and 'Walk' in sh:
            meta['sh'] = 1
            diff = {k: v for k, v in sh.items() if normal.get(k) != v}
            if diff:
                meta['sa'] = diff
            miss = [k for k in normal if k not in sh]
            if miss:
                meta['sm'] = miss
    return meta


def main():
    meta, plates = {}, []
    for form, typ, name in PLATES:
        pid = 26000 + int(form)
        m = download(f'0493/{form}', os.path.join(fs.OUT_ASSETS, str(pid)))
        plates.append({'type': typ, 'name': name, 'spr': pid if m else 0})
        if m:
            meta[pid] = m
        print(f'  {pid} {name}: {"sprites" if m else "none"}')
    m = download('0890/0001', os.path.join(fs.OUT_ASSETS, '27890'))
    if m:
        meta[27890] = m
    print('  27890 Eternamax:', 'sprites' if m else 'none')
    lines = [
        '/* ============ more-forms.js — GENERATED by tools/fetch_more_forms.py, do not edit ============',
        ' * Arceus\'s plate forms (systems/plates.js) and Eternamax Eternatus (systems/eternatus.js).',
        ' */',
        'Object.assign(G.SPRITE_META, ' + json.dumps({str(k): v for k, v in meta.items()}, separators=(',', ':')) + ');',
        'G.PLATES = ' + json.dumps(plates, separators=(',', ':')) + ';',
        '',
    ]
    with io.open(OUT_JS, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print('Wrote', OUT_JS)


if __name__ == '__main__':
    main()
