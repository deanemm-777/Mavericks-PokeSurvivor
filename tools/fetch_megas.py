#!/usr/bin/env python3
"""
Standalone build: Mega Evolution / Primal Reversion forms from SpriteCollab.

Every Pokémon that has a Mega or Primal form listed in SpriteCollab's
tracker.json gets an entry in js/data/megas.js. Forms with full sprites
(Idle, Walk, Attack) are downloaded, normal and shiny, to
assets/pokemon/{20000 + dex}/ and their metadata is added to G.SPRITE_META
under that same pseudo-number, so the regular sprite code draws them.
Forms without full sprites still Mega Evolve in game, with the normal sprite
and a Mega aura.

    python3 tools/fetch_megas.py

Source: https://github.com/PMDCollab/SpriteCollab (CC BY-NC 4.0)
"""
import io
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fetch_sprites as fs  # noqa: E402  (reuses fetch, parse_animdata, download_set)

OFFSET = 20000
SKIP = re.compile(r'Altcolor|Shadow|Baby|Skytemple|Stretchy|Droopy|Original|Alternate', re.I)
PREFER = ['Mega', 'Mega_X', 'Mega_Y', 'Primal', 'Mega_Z']
OUT_JS = os.path.join(fs.ROOT, 'js', 'data', 'megas.js')


def display(name, form):
    if form.startswith('Primal'):
        return 'Primal ' + name
    suffix = {'Mega_X': ' X', 'Mega_Y': ' Y', 'Mega_Z': ' Z'}.get(form, '')
    return 'Mega ' + name + suffix


def main():
    dex_names = {}
    src = open(os.path.join(fs.ROOT, 'js', 'data', 'pokedex.js'), encoding='utf-8').read()
    for m in re.finditer(r'"dex":(\d+),"name":"([^"]+)"', src):
        dex_names[int(m.group(1))] = m.group(2)

    print('Reading SpriteCollab tracker.json...')
    tracker = json.loads(fs.fetch(fs.RAW + '/tracker.json').decode('utf-8'))
    chosen = {}
    for key, e in tracker.items():
        dex = int(key)
        forms = []
        for fid, f in e.get('subgroups', {}).items():
            nm = f.get('name', '')
            if not re.match(r'(Mega|Primal)', nm) or SKIP.search(nm):
                continue
            full = fs.REQUIRED <= set(f.get('sprite_files', {}))
            shiny = {'Idle', 'Walk'} <= set(f.get('subgroups', {}).get('0001', {}).get('sprite_files', {}))
            rank = PREFER.index(nm) if nm in PREFER else 9
            forms.append((not full, rank, fid, nm, full, shiny))
        if forms and dex in dex_names:
            forms.sort()
            _, _, fid, nm, full, shiny = forms[0]
            chosen[dex] = {'fid': fid, 'form': nm, 'full': full, 'shiny': shiny}
    print(f'{len(chosen)} Pokemon with a Mega/Primal form, {sum(1 for c in chosen.values() if c["full"])} with sprites')

    out = {}
    for dex, c in sorted(chosen.items()):
        entry = {'n': display(dex_names[dex], c['form'])}
        if c['full']:
            tag = f'{dex:04d}/{c["fid"]}'
            xml = fs.fetch(f'{fs.BASE}/{tag}/AnimData.xml')
            if xml:
                anims, shadow = fs.parse_animdata(xml.decode('utf-8', 'replace'))
                out_dir = os.path.join(fs.OUT_ASSETS, str(OFFSET + dex))
                normal = fs.download_set(f'{fs.BASE}/{tag}', out_dir, anims)
                if fs.REQUIRED & set(normal):
                    meta = {'s': shadow, 'a': normal}
                    if c['shiny']:
                        sxml = fs.fetch(f'{fs.BASE}/{tag}/0001/AnimData.xml')
                        sanims = fs.parse_animdata(sxml.decode('utf-8', 'replace'))[0] if sxml else anims
                        shiny = fs.download_set(f'{fs.BASE}/{tag}/0001', os.path.join(out_dir, 's'), sanims, normal)
                        if 'Idle' in shiny and 'Walk' in shiny:
                            meta['sh'] = 1
                            diff = {k: v for k, v in shiny.items() if normal.get(k) != v}
                            if diff:
                                meta['sa'] = diff
                            miss = [k for k in normal if k not in shiny]
                            if miss:
                                meta['sm'] = miss
                    entry['spr'] = OFFSET + dex
                    entry['meta'] = meta
                    print(f'  {dex:4d} {entry["n"]}: sprites{" + shiny" if meta.get("sh") else ""}')
        out[dex] = entry

    lines = [
        '/* ============ megas.js — GENERATED by tools/fetch_megas.py, do not edit ============',
        ' * Pokémon that can Mega Evolve (or Primal Revert) in the standalone build.',
        ' *   n     name of the form',
        ' *   spr   pseudo Pokédex number of its sprites (20000 + dex), when drawn in SpriteCollab',
        ' * The sprite metadata is merged into G.SPRITE_META under that number.',
        ' */',
        'G.MEGAS = {',
    ]
    for dex, e in out.items():
        lines.append(f'  {dex}: {json.dumps({k: v for k, v in e.items() if k != "meta"}, separators=(",", ":"))},')
    lines += ['};', '(() => {', '  const META = {']
    for dex, e in out.items():
        if 'meta' in e:
            lines.append(f'    {e["spr"]}: {json.dumps(e["meta"], separators=(",", ":"))},')
    lines += ['  };', '  Object.assign(G.SPRITE_META, META);', '})();', '']
    with io.open(OUT_JS, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print(f'Wrote {OUT_JS}')


if __name__ == '__main__':
    main()
