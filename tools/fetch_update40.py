#!/usr/bin/env python3
"""
Standalone build: forms added with Doofcraft's update 40.

  - Black Kyurem / White Kyurem (Kyurem's fusions) from SpriteCollab 0646/0001
    and 0646/0002, under pseudo numbers 22646 and 23646
  - Shadow Mega Mewtwo Y, Shadow Mega Tyranitar, Shadow Mega Rayquaza and
    Shadow Black / White Kyurem: recoloured copies (tools/shadow_recolor.py)
    of the Mega / fusion sheets, under 21150, 21248, 21384, 24646, 25646
  - Mega Charizard Y as Charizard's second Mega (no SpriteCollab sprite: it
    keeps Charizard's sprite with the Mega aura)

Writes js/data/extra-forms.js (sprite metadata and the extra G.MEGAS entries).

    python3 tools/fetch_update40.py
    python3 tools/shadow_recolor.py 21150 21248 21384 24646 25646
"""
import io
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fetch_sprites as fs  # noqa: E402

DOWNLOAD = {22646: '0646/0001', 23646: '0646/0002'}
COPIES = {21150: 20150, 21248: 20248, 21384: 20384, 24646: 22646, 25646: 23646}
OUT_JS = os.path.join(fs.ROOT, 'js', 'data', 'extra-forms.js')


def download(tag, out_dir):
    xml = fs.fetch(f'{fs.BASE}/{tag}/AnimData.xml')
    anims, shadow = fs.parse_animdata(xml.decode('utf-8', 'replace'))
    normal = fs.download_set(f'{fs.BASE}/{tag}', out_dir, anims)
    meta = {'s': shadow, 'a': normal}
    sxml = fs.fetch(f'{fs.BASE}/{tag}/0001/AnimData.xml')
    if sxml:
        sanims = fs.parse_animdata(sxml.decode('utf-8', 'replace'))[0]
        sh = fs.download_set(f'{fs.BASE}/{tag}/0001', os.path.join(out_dir, 's'), sanims, normal)
        if 'Idle' in sh and 'Walk' in sh:
            meta['sh'] = 1
            diff = {k: v for k, v in sh.items() if normal.get(k) != v}
            if diff:
                meta['sa'] = diff
            miss = [k for k in normal if k not in sh]
            if miss:
                meta['sm'] = miss
    return meta


def mega_meta():
    """Sprite metadata of the existing Megas (js/data/megas.js)."""
    src = open(os.path.join(fs.ROOT, 'js', 'data', 'megas.js'), encoding='utf-8').read()
    out = {}
    for m in re.finditer(r'^\s+(2\d{4}): (\{.*\}),$', src, re.M):
        out[int(m.group(1))] = json.loads(m.group(2))
    return out


def main():
    meta = {}
    for pid, tag in DOWNLOAD.items():
        meta[pid] = download(tag, os.path.join(fs.OUT_ASSETS, str(pid)))
        print(f'  {pid}: {tag}{" + shiny" if meta[pid].get("sh") else ""}')
    mm = mega_meta()
    for pid, src in COPIES.items():
        meta[pid] = json.loads(json.dumps(meta.get(src) or mm[src]))
    megas = {
        646: {'n': 'Black Kyurem', 'spr': 22646, 'fusion': 1, 'alt': {'n': 'White Kyurem', 'spr': 23646}},
        31150: {'n': 'Shadow Mega Mewtwo Y', 'spr': 21150},
        31248: {'n': 'Shadow Mega Tyranitar', 'spr': 21248},
        31384: {'n': 'Shadow Mega Rayquaza', 'spr': 21384},
        31646: {'n': 'Shadow Black Kyurem', 'spr': 24646, 'fusion': 1, 'alt': {'n': 'Shadow White Kyurem', 'spr': 25646}},
    }
    lines = [
        '/* ============ extra-forms.js — GENERATED by tools/fetch_update40.py, do not edit ============',
        ' * Forms from Doofcraft\'s update 40: Kyurem\'s fusions, Shadow Megas and Mega Charizard Y.',
        ' *   alt     the second form (Charizard Y, White Kyurem): Mega Evolutions alternate between the two',
        ' *   fusion  a fusion lasts until the end of the run',
        ' */',
        'Object.assign(G.SPRITE_META, ' + json.dumps({str(k): v for k, v in meta.items()}, separators=(',', ':')) + ');',
        'Object.assign(G.MEGAS, ' + json.dumps({str(k): v for k, v in megas.items()}, separators=(',', ':')) + ');',
        'if (G.MEGAS[6]) G.MEGAS[6].alt = { n: \'Mega Charizard Y\', spr: 0 };   // no sprite: Charizard\'s, with the Mega aura',
        '',
    ]
    with io.open(OUT_JS, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print('Wrote', OUT_JS)


if __name__ == '__main__':
    main()
