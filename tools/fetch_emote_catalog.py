#!/usr/bin/env python3
"""
Standalone build (Doofcraft update 40): the emote catalog. Emotes are
SpriteCollab portraits (each Pokémon's faces: Happy, Angry, Crying...), normal
and shiny. This writes which faces exist for each Pokédex number as bit masks;
the images themselves are loaded from SpriteCollab when you get one, and kept
offline by sw.js.  Writes js/data/emotes.js.

    python3 tools/fetch_emote_catalog.py
"""
import io, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fetch_sprites as fs  # noqa: E402

NAMES = ['Normal', 'Happy', 'Pain', 'Angry', 'Worried', 'Sad', 'Crying', 'Shouting', 'Teary-Eyed', 'Determined',
         'Joyous', 'Inspired', 'Surprised', 'Dizzy', 'Sigh', 'Stunned']


def main():
    t = json.loads(fs.fetch(fs.RAW + '/tracker.json').decode('utf-8'))
    cat = []
    for d in range(1, 1026):
        e = t.get(f'{d:04d}', {})
        m = sum(1 << i for i, n in enumerate(NAMES) if n in e.get('portrait_files', {}))
        sh = e.get('subgroups', {}).get('0000', {}).get('subgroups', {}).get('0001', {}).get('portrait_files', {})
        s = sum(1 << i for i, n in enumerate(NAMES) if n in sh)
        cat.append([m, s])
    with io.open(os.path.join(fs.ROOT, 'js', 'data', 'emotes.js'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('/* ============ emotes.js — GENERATED by tools/fetch_emote_catalog.py, do not edit ============\n'
                ' * G.EMOTE_CAT[dex - 1] = [faces, shiny faces], bit i = G.EMOTE_NAMES[i] (SpriteCollab portraits).\n */\n')
        f.write('G.EMOTE_NAMES = ' + json.dumps(NAMES) + ';\n')
        f.write('G.EMOTE_CAT = ' + json.dumps(cat, separators=(',', ':')) + ';\n')
    print('Wrote js/data/emotes.js:', sum(bin(a).count('1') + bin(b).count('1') for a, b in cat), 'emotes')


if __name__ == '__main__':
    main()
